/*Escreva um programa que receba um número e verifique se ele está no intervalo 
entre 10 e 20 (inclusive). Exiba no console se o número está ou não no intervalo.*/

var numeroUsuario = 15

if (numeroUsuario >= 10 && numeroUsuario <= 20) {
    console.log("O número informado esta no intervalo entre 10 e 20")
}else {
    console.log("O número informado esta fora do intervalo entre 10 e 20")
}